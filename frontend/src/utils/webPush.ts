/**
 * Converts a base64 string to a Uint8Array for the PushManager applicationServerKey.
 */
export function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4)
  const base64 = (base64String + padding)
    .replace(/-/g, '+')
    .replace(/_/g, '/')

  const rawData = window.atob(base64)
  const outputArray = new Uint8Array(rawData.length)

  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i)
  }
  return outputArray
}

export interface PushSubscriptionStatus {
  supported: boolean
  permission: NotificationPermission
  isSubscribed: boolean
  subscription: PushSubscription | null
}

/**
 * Checks current Web Push support, notification permission, and active subscription.
 */
export async function getPushSubscriptionStatus(): Promise<PushSubscriptionStatus> {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator) || !('PushManager' in window)) {
    return {
      supported: false,
      permission: 'denied',
      isSubscribed: false,
      subscription: null
    }
  }

  const permission = Notification.permission
  const registration = await navigator.serviceWorker.ready
  const subscription = await registration.pushManager.getSubscription()

  return {
    supported: true,
    permission,
    isSubscribed: subscription !== null,
    subscription
  }
}

/**
 * Subscribes the current device to Web Push and saves the subscription to Supabase.
 */
export async function subscribeToPush(userId?: string | null): Promise<{ success: boolean; error?: string }> {
  try {
    if (!('serviceWorker' in navigator) || !('PushManager' in window)) {
      return { success: false, error: 'Web Push is not supported in this browser' }
    }

    const permission = await Notification.requestPermission()
    if (permission !== 'granted') {
      return { success: false, error: 'Notification permission was denied' }
    }

    const registration = await navigator.serviceWorker.ready
    let subscription = await registration.pushManager.getSubscription()

    if (!subscription) {
      const applicationServerKey = urlBase64ToUint8Array(VAPID_PUBLIC_KEY)
      subscription = await registration.pushManager.subscribe({
        userVisibleOnly: true,
        applicationServerKey
      })
    }

    const subscriptionJson = subscription.toJSON()
    const p256dh = subscriptionJson.keys?.p256dh
    const auth = subscriptionJson.keys?.auth

    if (!subscription.endpoint || !p256dh || !auth) {
      return { success: false, error: 'Incomplete push keys generated by browser' }
    }

    // Persist to Supabase push_subscriptions table
    if (supabase) {
      const payload: any = {
        endpoint: subscription.endpoint,
        p256dh,
        auth,
        updated_at: new Date().toISOString()
      }
      if (userId && typeof userId === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(userId)) {
        payload.user_id = userId
      }

      const { error: dbErr } = await supabase
        .from('push_subscriptions')
        .upsert(payload, { onConflict: 'endpoint' })

      if (dbErr) {
        console.warn('Could not persist push subscription to database:', dbErr.message)
      }
    }

    return { success: true }
  } catch (err: any) {
    console.error('Failed to subscribe to Web Push:', err)
    return { success: false, error: err?.message || 'Subscription failed' }
  }
}

/**
 * Unsubscribes from Web Push and removes subscription from Supabase.
 */
export async function unsubscribeFromPush(userId?: string | null): Promise<boolean> {
  try {
    if (!('serviceWorker' in navigator) || !('PushManager' in window)) return false

    const registration = await navigator.serviceWorker.ready
    const subscription = await registration.pushManager.getSubscription()

    if (subscription) {
      const endpoint = subscription.endpoint
      await subscription.unsubscribe()

      if (supabase) {
        await supabase
          .from('push_subscriptions')
          .delete()
          .eq('endpoint', endpoint)
      }
    }
    return true
  } catch (err) {
    console.error('Failed to unsubscribe from Web Push:', err)
    return false
  }
}
